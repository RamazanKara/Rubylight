//! The same SDL fragment passes compiled for the selected desktop GPU API.
use sdl3_sys::everything::*;

#[derive(Clone, Copy)]
pub(super) enum Shader {
    Upscale,
    Wavelet,
    #[cfg(unix)]
    Planes,
    Packed,
}

impl Shader {
    #[cfg(windows)]
    pub fn filter_hlsl(self) -> &'static [u8] {
        match self {
            Self::Upscale => include_bytes!("../upscale.hlsl"),
            Self::Wavelet => include_bytes!("../pyrowave.hlsl"),
            _ => unreachable!("not a texture filter"),
        }
    }

    pub fn info(self) -> SDL_GPUShaderCreateInfo {
        #[cfg(target_os = "macos")]
        let (code, entrypoint, format): (&[u8], _, _) = (
            match self {
                Self::Upscale => include_bytes!("../metal/upscale.metal"),
                Self::Wavelet => include_bytes!("../metal/pyrowave.metal"),
                Self::Planes => include_bytes!("../metal/pyrowave-planes.metal"),
                Self::Packed => include_bytes!("../metal/packed444.metal"),
            },
            c"nightjar_fragment",
            SDL_GPU_SHADERFORMAT_MSL,
        );
        #[cfg(not(target_os = "macos"))]
        let (code, entrypoint, format): (&[u8], _, _) = match self {
            Self::Upscale => (
                include_bytes!("../upscale.spv"),
                c"fragment",
                SDL_GPU_SHADERFORMAT_SPIRV,
            ),
            Self::Wavelet => (
                include_bytes!("../pyrowave.spv"),
                c"fragment",
                SDL_GPU_SHADERFORMAT_SPIRV,
            ),
            #[cfg(unix)]
            Self::Planes => (
                include_bytes!("../pyrowave-planes.spv"),
                c"planes",
                SDL_GPU_SHADERFORMAT_SPIRV,
            ),
            Self::Packed => (
                include_bytes!("../packed444.spv"),
                c"fragment",
                SDL_GPU_SHADERFORMAT_SPIRV,
            ),
        };
        SDL_GPUShaderCreateInfo {
            code: code.as_ptr(),
            code_size: code.len(),
            entrypoint: entrypoint.as_ptr(),
            format,
            stage: SDL_GPU_SHADERSTAGE_FRAGMENT,
            num_samplers: match self {
                Self::Packed => 0,
                #[cfg(unix)]
                Self::Planes => 3,
                _ => 1,
            },
            num_uniform_buffers: 1,
            num_storage_buffers: u32::from(matches!(self, Self::Packed)),
            ..Default::default()
        }
    }
}

#[cfg(test)]
mod tests {
    use sha2::{Digest, Sha256};

    /// macOS draws with SPIRV-Cross translations of the SPIR-V the other platforms load. A changed
    /// `.spv` fails here on any platform until `metal/generate.py` translates it again.
    #[test]
    fn the_metal_passes_are_translated_from_the_shipped_spirv() {
        for (name, spirv, metal) in [
            ("upscale", &include_bytes!("../upscale.spv")[..], include_str!("../metal/upscale.metal")),
            ("pyrowave", include_bytes!("../pyrowave.spv"), include_str!("../metal/pyrowave.metal")),
            ("pyrowave-planes", include_bytes!("../pyrowave-planes.spv"), include_str!("../metal/pyrowave-planes.metal")),
            ("packed444", include_bytes!("../packed444.spv"), include_str!("../metal/packed444.metal")),
        ] {
            let digest: String = Sha256::digest(spirv).iter().map(|byte| format!("{byte:02x}")).collect();
            assert_eq!(
                metal.lines().next(),
                Some(format!("// Generated by generate.py from {name}.spv (SHA-256 {digest})").as_str()),
                "{name}.metal is stale: run `python3 desktop/src/metal/generate.py <spirv-cross>` from protocol/ (SPIRV-Cross vulkan-sdk-1.4.321.0)"
            );
        }
    }
}

"""Rebuild the SDL Metal fragment shaders from Nightjar's shipped SPIR-V.

Usage: python3 generate.py [spirv-cross]. Generated with SPIRV-Cross
vulkan-sdk-1.4.321.0. The app build does not need the shader compiler.
"""
from pathlib import Path
import re
import subprocess
import sys

dest = Path(__file__).resolve().parent
compiler = sys.argv[1] if len(sys.argv) > 1 else "spirv-cross"
for shader, entry in (("upscale", "fragment"), ("pyrowave", "fragment"), ("pyrowave-planes", "planes"), ("packed444", "fragment")):
    code = subprocess.check_output([
        compiler, dest.parent / (shader + ".spv"), "--msl", "--msl-version", "20100",
        "--msl-decoration-binding", "--rename-entry-point", entry, "nightjar_fragment", "frag",
    ], text=True)
    if shader == "packed444":
        # Vulkan puts storage and uniforms in different sets. SDL Metal numbers
        # them together, with the single uniform buffer at 0 and storage at 1.
        code, count = re.subn(r"(const device [^,]+?)\[\[buffer\(0\)\]\]", r"\1[[buffer(1)]]", code)
        if count != 1:
            raise ValueError("Packed shader storage buffer layout changed")
    (dest / (shader + ".metal")).write_text(
        f"// Generated by generate.py from {shader}.spv\n" + code.rstrip("\n") + "\n"
    )

#!/usr/bin/env python3
"""Generates the design tokens for every client from design/tokens.json, the one source of the numbers.

Writes Android resources, Rust constants for the desktop client and CSS custom properties for the site. The output
is committed. CI runs --check, so a token changed in one place can't drift from the others.

  python scripts/gen_design_tokens.py [--check]
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "design/tokens.json"
ANDROID = ROOT / "app/src/main/res/values/design_tokens.xml"
RUST = ROOT / "protocol/desktop/src/ui/design_tokens.rs"
CSS = ROOT / "site/assets/design-tokens.css"

NOTE = "Generated by scripts/gen_design_tokens.py from design/tokens.json. Do not edit."

DP_GROUPS = {"radius", "space", "size", "layout"}
DP_LAST = {
    "blur", "shadowY", "shadowBlur", "rimWidth", "lensWidth", "lensBlur", "gap", "gapTv", "ringWidth", "ringWidthTv",
    "haloBlur", "haloBlurTv", "glowBlur",
}
INT_LAST = {"ms", "navMaxMs", "firstFeedbackFrames", "frames", "weight", "bakedThumbW", "bakedThumbH"}


def kind(key, value):
    """What a token is: color, string, dp, sp, int or float. The name decides, so a value can't change its unit."""
    if isinstance(value, str):
        return "color" if value.startswith("#") else "string"
    parts = key.split(".")
    if parts[0] == "type" and parts[-1] in ("size", "line"):
        return "sp"
    if parts[0] in DP_GROUPS or parts[-1] in DP_LAST:
        return "dp"
    if parts[-1] in INT_LAST:
        return "int"
    return "float"


def rgba(value):
    """(r, g, b, a) of #RRGGBB or #RRGGBBAA."""
    if not re.fullmatch(r"#(?:[0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})", value):
        raise ValueError(f"not a colour: {value}")
    hex_digits = value[1:] + ("FF" if len(value) == 7 else "")
    return tuple(int(hex_digits[i:i + 2], 16) for i in range(0, 8, 2))


def android_color(value):
    """Android writes alpha first: #RRGGBBAA in the tokens is #AARRGGBB in a resource."""
    r, g, b, a = rgba(value)
    return f"#{r:02X}{g:02X}{b:02X}" if a == 255 else f"#{a:02X}{r:02X}{g:02X}{b:02X}"


def premultiplied(value):
    """egui's Color32 holds premultiplied alpha."""
    r, g, b, a = rgba(value)
    return tuple(round(c * a / 255) for c in (r, g, b)) + (a,)


def snake(key):
    """glass.chrome.lens.rimTop to glass_chrome_lens_rim_top."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", key.replace(".", "_")).lower()


def number(value):
    """A number without a float's trailing .0, as resources and CSS write it."""
    return str(int(value)) if float(value).is_integer() else repr(float(value))


def android(tokens):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {NOTE} -->", "<resources>"]
    for key, value in tokens.items():
        name = "nj_" + snake(key)
        token_kind = kind(key, value)
        if token_kind == "color":
            lines.append(f'    <color name="{name}">{android_color(value)}</color>')
        elif token_kind == "string":
            lines.append(f'    <string name="{name}" translatable="false">{value}</string>')
        elif token_kind in ("dp", "sp"):
            lines.append(f'    <dimen name="{name}">{number(value)}{token_kind}</dimen>')
        elif token_kind == "int":
            lines.append(f'    <integer name="{name}">{int(value)}</integer>')
        else:
            lines.append(f'    <item name="{name}" type="dimen" format="float">{float(value)!r}</item>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def rust(tokens):
    lines = [
        f"//! {NOTE}",
        "",
        "#[rustfmt::skip]",
        "#[allow(dead_code)]",
        "mod values {",
        "    use egui::Color32;",
    ]
    for key, value in tokens.items():
        name = snake(key).upper()
        token_kind = kind(key, value)
        if token_kind == "color":
            r, g, b, a = premultiplied(value)
            lines.append(f"    pub const {name}: Color32 = Color32::from_rgba_premultiplied({r}, {g}, {b}, {a});")
        elif token_kind == "string":
            lines.append(f'    pub const {name}: &str = "{value}";')
        elif token_kind == "int":
            lines.append(f"    pub const {name}: u32 = {int(value)};")
        else:
            lines.append(f"    pub const {name}: f32 = {float(value)!r};")
    lines += ["}", "", "#[allow(unused_imports)]", "pub use values::*;"]
    return "\n".join(lines) + "\n"


def css(tokens):
    lines = [f"/* {NOTE} */", ":root {"]
    for key, value in tokens.items():
        name = "--nj-" + snake(key).replace("_", "-")
        token_kind = kind(key, value)
        if token_kind == "color":
            text = value.upper()
        elif token_kind == "string":
            text = f'"{value}"'
        elif token_kind in ("dp", "sp"):
            text = f"{number(value)}px"
        elif key.split(".")[-1] == "ms":
            text = f"{int(value)}ms"
        else:
            text = number(value)
        lines.append(f"  {name}: {text};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def outputs(tokens):
    return {ANDROID: android(tokens), RUST: rust(tokens), CSS: css(tokens)}


def load():
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    return {key: value for key, value in tokens.items() if not key.startswith("$")}


def main(argv):
    results = outputs(load())
    if "--check" in argv:
        stale = [path for path, text in results.items() if not path.exists() or path.read_bytes() != text.encode()]
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run python scripts/gen_design_tokens.py)")
        return 1 if stale else 0
    for path, text in results.items():
        path.write_bytes(text.encode())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
